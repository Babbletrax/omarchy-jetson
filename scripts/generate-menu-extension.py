#!/usr/bin/env python3
"""Generate the packaged Omarchy menu extension for this build.

The upstream menu ships 320 items whose actions call roughly 164 omarchy-*
commands. This build packages only a subset, so most entries would render and
then do nothing. Rather than fork the menu or hand-maintain a deny list, every
entry whose action calls omarchy-* commands gets a `when:` guard requiring
those commands on PATH. The shell evaluates guards at load, so an entry
disappears while its command is absent and returns by itself once the command
is packaged.

Guards are generated from the pinned upstream menu, so regenerate this file
whenever the Omarchy pin moves:

    scripts/generate-menu-extension.py \
      --upstream /usr/share/omarchy/default/omarchy/omarchy-menu.jsonc \
      --additions packages/omarchy-jetson-upstream/menu-additions.jsonc \
      --output packages/omarchy-jetson-upstream/default-menu-extension.jsonc
"""
from __future__ import annotations

import argparse
import json
import re
import sys

COMMAND = re.compile(r"\bomarchy-[a-z0-9-]+")


def load_jsonc(path: str) -> dict:
    raw = open(path, encoding="utf-8").read()
    raw = re.sub(r"^\s*//[^\n]*$", "", raw, flags=re.M)
    raw = re.sub(r",(\s*[}\]])", r"\1", raw)
    parsed = json.loads(raw)
    return parsed.get("items", parsed)


def guard_for(entry: dict) -> str | None:
    """A `when:` expression requiring every command the action calls."""
    action = entry.get("action") or ""
    commands = sorted(set(COMMAND.findall(action)))
    if not commands:
        return None
    return " && ".join(f"command -v {c} >/dev/null" for c in commands)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream", required=True)
    ap.add_argument("--additions", required=True)
    ap.add_argument("--output", required=True)
    args = ap.parse_args()

    upstream = load_jsonc(args.upstream)
    additions = load_jsonc(args.additions)

    generated: dict[str, dict] = {}
    for item_id, entry in upstream.items():
        guard = guard_for(entry)
        if guard is None:
            continue
        # The shell merges field by field and normalizes every key, so a
        # partial override would blank the label and action. Copy the whole
        # entry and combine the guard with any guard upstream already set.
        merged = dict(entry)
        existing = (entry.get("when") or "").strip()
        merged["when"] = f"{existing} && {guard}" if existing else guard
        generated[item_id] = merged

    # Hand-written Jetson entries win over anything generated.
    items = {**generated, **additions}

    header = (
        "{\n"
        "  // GENERATED by scripts/generate-menu-extension.py -- do not edit.\n"
        "  //\n"
        "  // Jetson additions plus a `when:` guard on every upstream entry whose\n"
        "  // action calls omarchy-* commands. Entries hide while their command is\n"
        "  // absent and return once it is packaged, so the menu never shows an\n"
        "  // action that cannot run. Regenerate when the Omarchy pin moves.\n"
        f"  // upstream entries guarded: {len(generated)}; Jetson additions: {len(additions)}\n"
        '  "items": '
    )
    body = json.dumps(items, indent=2, ensure_ascii=False, sort_keys=True)
    body = "\n".join(("  " + line) if line else line for line in body.split("\n")).lstrip()
    open(args.output, "w", encoding="utf-8").write(header + body + "\n}\n")
    print(f"guarded {len(generated)} upstream entries, kept {len(additions)} Jetson additions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
